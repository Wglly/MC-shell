#!/bin/sh
# MC-shell installer — copies the shell into your Quickshell config directory
# and drops a `mc-shell` wrapper in ~/.local/bin so keybindings stay short.
set -eu

SRC=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
DEST="${XDG_CONFIG_HOME:-$HOME/.config}/quickshell/mc-shell"
BIN="${HOME}/.local/bin"

usage() {
    cat <<EOF
usage: $0 [--dir <target>] [--no-wrapper] [--uninstall]

  --dir <target>   install the shell into <target> (default: $DEST)
  --no-wrapper     do not create ~/.local/bin/mc-shell
  --uninstall      remove the installed copy and wrapper
EOF
}

TARGET="$DEST"
WRAPPER=1

while [ $# -gt 0 ]; do
    case "$1" in
        --dir) TARGET="$2"; shift 2 ;;
        --no-wrapper) WRAPPER=0; shift ;;
        --uninstall)
            rm -rf "$DEST" "$BIN/mc-shell"
            echo "removed $DEST and $BIN/mc-shell"
            exit 0
            ;;
        -h|--help) usage; exit 0 ;;
        *) echo "unknown argument: $1" >&2; usage; exit 1 ;;
    esac
done

command -v qs >/dev/null 2>&1 || {
    echo "error: quickshell (qs) is not installed" >&2
    exit 1
}

echo "==> installing MC-shell into $TARGET"
mkdir -p "$TARGET"
# keep the installed tree in sync without nuking anything unexpected
for item in shell.qml modules services assets README.md LICENSE; do
    [ -e "$SRC/$item" ] || continue
    rm -rf "$TARGET/$item"
    cp -a "$SRC/$item" "$TARGET/$item"
done

if [ "$WRAPPER" = "1" ]; then
    mkdir -p "$BIN"
    cat > "$BIN/mc-shell" <<EOF
#!/bin/sh
# MC-shell launcher/wrapper (generated by install.sh)
exec qs -p "$TARGET" "\$@"
EOF
    chmod +x "$BIN/mc-shell"
    echo "==> wrapper: $BIN/mc-shell"
    case ":$PATH:" in
        *":$BIN:"*) ;;
        *) echo "note: $BIN is not in PATH; add it or call the absolute path" ;;
    esac
else
    echo "==> run it with: qs -p $TARGET"
fi

cat <<EOF

Installed.  Start it with:

    mc-shell                 # or: qs -p $TARGET

Autostart:

    Hyprland : exec-once = mc-shell
    niri     : spawn-at-startup "mc-shell"

Keybindings (Hyprland):

    bind = SUPER, D, exec, mc-shell ipc call shell launcher
    bind = SUPER, X, exec, mc-shell ipc call shell control
    bind = SUPER, TAB, exec, mc-shell ipc call shell overview
    bind = , XF86AudioRaiseVolume,  exec, mc-shell ipc call shell volumeUp
    bind = , XF86AudioLowerVolume,  exec, mc-shell ipc call shell volumeDown
    bind = , XF86AudioMute,         exec, mc-shell ipc call shell volumeMute
    bind = , XF86MonBrightnessUp,   exec, mc-shell ipc call shell brightnessUp
    bind = , XF86MonBrightnessDown, exec, mc-shell ipc call shell brightnessDown

Keybindings (niri, config.kdl):

    Mod+D { spawn "mc-shell" "ipc" "call" "shell" "launcher"; }
    Mod+X { spawn "mc-shell" "ipc" "call" "shell" "control"; }
    Mod+Tab { spawn "mc-shell" "ipc" "call" "shell" "overview"; }
    XF86AudioRaiseVolume { spawn "mc-shell" "ipc" "call" "shell" "volumeUp"; }
    XF86AudioLowerVolume { spawn "mc-shell" "ipc" "call" "shell" "volumeDown"; }
    XF86AudioMute        { spawn "mc-shell" "ipc" "call" "shell" "volumeMute"; }

If another status bar is running, disable it first: MC-shell reserves the top
edge for itself.
EOF
